using MovieLibrary.Core.Matching;
using MovieLibrary.Web.Models;

namespace MovieLibrary.Web.Tests;

/// <summary>
/// The published JSON, as <c>CatalogWriter</c> actually emits it, read the way the browser reads it.
/// <para>
/// This is the one contract standing between the two serialisers. The writer uses camelCase with
/// <c>WhenWritingNull</c>; <c>GetFromJsonAsync</c> uses the web defaults, which happen to agree today. If
/// either side's naming policy changed, every field would come back at its default -- <c>I == 0</c> on every
/// record, so the whole library badged "Not matched" -- and nothing else in either suite would notice, because
/// every other test on both sides builds its objects in memory.
/// </para>
/// <para>
/// The fixture is generated by the writer and kept byte-identical to its output by
/// <c>MovieLibrary.Core.Tests.PublishedShapeFixtureTests</c>, which also says how to refresh it. It is
/// committed because the real catalogue is gitignored and CI therefore has no sample at all. This project
/// cannot reference the enrich project to generate it here, and should not: that is where TMDB_TOKEN is read.
/// </para>
/// <para>
/// <b>What it cannot catch, measured rather than assumed.</b> The web defaults set
/// <c>PropertyNameCaseInsensitive</c>, so a change between camelCase and PascalCase alone binds anyway and
/// this suite stays green -- the brief's "a naming change would present as I == 0 on every record" is only
/// true of a change that alters the LETTERS, such as camelCase to snake_case, or a field renamed outright.
/// Those are caught here, and the Core-side fixture test catches any writer change at all, including a
/// case-only one, because it compares bytes.
/// </para>
/// </summary>
public class PublishedShapeTests
{
    private static string Fixture()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "MovieLibrary.slnx"))) dir = dir.Parent;

        Assert.NotNull(dir);   // a test that silently cannot find the repo proves nothing
        var path = Path.Combine(dir.FullName, "tests", "fixtures", "movies-three-records.json");

        Assert.True(File.Exists(path),
            "The committed sample of the published shape is missing from " + path + ". It is generated by "
            + "CatalogWriter in MovieLibrary.Core.Tests.PublishedShapeFixtureTests, which prints the exact "
            + "bytes to write when it is absent.");

        return File.ReadAllText(path);
    }

    [Fact]
    public async Task ThePublishedShapeDeserialisesThroughTheServiceWithEveryFieldIntact()
    {
        var stub = new StubCatalog().Serves(StubCatalog.Movies, StubCatalog.Json(Fixture()));

        var result = await stub.Service().GetMoviesAsync();

        Assert.Equal(CatalogState.Ready, result.State);
        Assert.Equal(3, result.Value.Count);

        var confident = result.Value[0];
        Assert.Equal(807, confident.I);
        Assert.Equal("807-110", confident.K);
        Assert.Equal("Se7en", confident.T);
        Assert.Equal(1995, confident.Y);
        Assert.Equal(110, confident.Rt);
        Assert.Equal("/se7en.jpg", confident.P);
        Assert.Equal([80, 9648], confident.G);
        Assert.Equal("Thriller", confident.Ag);
        Assert.Equal(8.4, confident.Vote);
        Assert.Equal(["David Fincher"], confident.Dir);
        Assert.Equal("Seven deadly sins.", confident.Tag);
        Assert.Equal("Blu-ray", confident.Own);
        Assert.Equal(0.95, confident.Mc);
        Assert.Equal("Morgan Freeman", Assert.Single(confident.Cast).N);
    }

    /// <remarks>
    /// The writer drops a null field entirely rather than writing <c>null</c>, so the browser meets ABSENT
    /// properties and not null ones. A record that only ever came from an in-memory object would never exercise
    /// that, and the arrays are the half that would hurt: an absent array deserialising to null rather than to
    /// an empty one is a NullReferenceException on the first tile Task 6 renders.
    /// </remarks>
    [Fact]
    public async Task AFieldTheWriterOmittedBecauseItWasNullComesBackAsNullAndTheArraysAreStillThere()
    {
        var stub = new StubCatalog().Serves(StubCatalog.Movies, StubCatalog.Json(Fixture()));

        var result = await stub.Service().GetMoviesAsync();
        var sparse = result.Value[1];

        Assert.Null(sparse.P);
        Assert.Null(sparse.B);
        Assert.Null(sparse.Ov);
        Assert.Null(sparse.Tag);
        Assert.Null(sparse.Col);
        Assert.Null(sparse.Own);
        Assert.NotNull(sparse.Dir);
        Assert.Empty(sparse.Dir);
        Assert.NotNull(sparse.Cast);
        Assert.Empty(sparse.Cast);
        Assert.Null(result.Value[2].Y);   // an unlisted film has no year at all
    }

    /// <remarks>
    /// The assertion that actually fails on a naming mismatch. Every other check above would fail too, but this
    /// is the one that says WHY it matters: a mismatch presents as I == 0 everywhere, which is the whole library
    /// badged "Not matched", and a reader looking at that symptom would go hunting in the pipeline.
    /// </remarks>
    [Fact]
    public async Task TheBandsSurviveTheRoundTripSoANamingMismatchCannotBadgeEverythingNotMatched()
    {
        var stub = new StubCatalog().Serves(StubCatalog.Movies, StubCatalog.Json(Fixture()));

        var result = await stub.Service().GetMoviesAsync();

        Assert.Equal(
            new[] { Confidence.Confident, Confidence.Uncertain, Confidence.Unmatched },
            result.Value.Select(ConfidenceBand.Of));
    }
}
