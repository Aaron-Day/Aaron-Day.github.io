using MovieLibrary.Core.Matching;
using MovieLibrary.Core.Models;
using MovieLibrary.Enrich.Emit;

namespace MovieLibrary.Core.Tests;

/// <summary>
/// Keeps <c>tests/fixtures/movies-three-records.json</c> byte-identical to what <see cref="CatalogWriter"/>
/// emits, so the browser side has one committed sample of the REAL published shape to deserialise.
/// <para>
/// Nothing anywhere pinned that the published JSON deserialises at all. The writer uses camelCase with
/// <c>WhenWritingNull</c> and <c>GetFromJsonAsync</c>'s web defaults happen to agree with it today -- but a
/// naming-policy change on either side would present as <c>I == 0</c> on every record, which is the whole
/// library badged "Not matched", with nothing going red. Dropping the plan's 1,265/171/20 count assertion was
/// right; dropping the SHAPE test with it was not.
/// </para>
/// <para>
/// The fixture is generated BY the writer rather than written by hand, so it cannot drift from what the
/// pipeline emits: this test regenerates it and compares, and says how to refresh it when the writer changes
/// on purpose. It is committed because the real catalogue is gitignored, so CI has no other sample.
/// </para>
/// </summary>
public class PublishedShapeFixtureTests : IDisposable
{
    /// <summary>One record per band, which is the only thing the three are chosen for.</summary>
    internal static IReadOnlyList<MovieRecord> ThreeBands() =>
    [
        // Confident: a real match, well above the accept threshold, with every optional field populated.
        new(807, "807-110", "Se7en", 1995, 110, "/se7en.jpg", "/se7en-bd.jpg", [80, 9648], "Thriller", 8.4,
            ["David Fincher"], "Two detectives hunt a serial killer.", "Seven deadly sins.",
            [new CastMember("Morgan Freeman", "Somerset", "/mf.jpg")], "Fincher", "Blu-ray", 0.95),

        // Needs review: the right id with a low score, and the nullable fields left null so the writer's
        // WhenWritingNull drops them and the browser has to cope with their absence rather than with nulls.
        // It also carries a sort title, because "The Peeled Edition" is exactly the case Srt exists for.
        new(601, "601-88", "The Peeled Edition", 1982, 88, null, null, [18], "Drama", 6.2,
            [], null, null, [], null, null, 0.55, Srt: "Peeled Edition"),

        // Not matched: id 0, keyed by content hash, score 0 even though a candidate may have scored.
        // Its Ex map is the one sample of an owner-added field in the published shape.
        new(0, "u-d2f1c6e2", "An Unlisted Film", null, 101, null, null, [], "Documentary", 0d,
            ["A Director"], null, null, [], null, null, 0d,
            Ex: new Dictionary<string, string> { ["Purchase Date"] = "2019-03-14" }),
    ];

    public const string FixtureName = "movies-three-records.json";

    private readonly string _dir = Path.Combine(Path.GetTempPath(), "ml-fixture-" + Guid.NewGuid());
    public void Dispose() { if (Directory.Exists(_dir)) Directory.Delete(_dir, true); }

    internal static string FixturePath()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "MovieLibrary.slnx"))) dir = dir.Parent;

        Assert.NotNull(dir);   // a test that silently cannot find the repo proves nothing
        return Path.Combine(dir.FullName, "tests", "fixtures", FixtureName);
    }

    private static CatalogMeta Meta() =>
        new("2026-11-04T09:00:00Z", 3, 0, 0, new() { ["18"] = "Drama" }, CatalogMeta.TmdbAttribution, []);

    [Fact]
    public async Task TheCommittedFixtureIsExactlyWhatTheWriterEmits()
    {
        await new CatalogWriter(_dir).WriteAsync(ThreeBands(), [], Meta(), CancellationToken.None);
        var emitted = await File.ReadAllTextAsync(Path.Combine(_dir, "movies.json"));

        var path = FixturePath();
        Assert.True(File.Exists(path),
            $"The committed fixture is missing. Write this to {path}, verbatim:\n{emitted}");

        Assert.Equal(emitted, await File.ReadAllTextAsync(path), ignoreLineEndingDifferences: false);
    }

    [Fact]
    public void TheFixtureCoversAllThreeBandsAndWouldBeWorthlessIfItDidNot()
    {
        // A sample that happened to hold three confident records would deserialise just as well and prove
        // nothing about the band rule or about a missing optional field.
        Assert.Equal(
            new[] { Confidence.Confident, Confidence.Uncertain, Confidence.Unmatched },
            ThreeBands().Select(ConfidenceBand.Of));
    }
}
